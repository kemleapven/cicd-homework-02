set -e

echo "=== 1. Updating System Packages ==="
sudo apt-get update -y
sudo apt-get install -y ca-certificates curl gnupg lsb-release

echo "=== 2. Installing Official Docker Engine ==="
sudo install -m 0755 -d /etc/apt/keyrings
if [ ! -f /etc/apt/keyrings/docker.gpg ]; then
    curl -fsSL https://download.docker.com/linux/ubuntu/gpg | sudo gpg --dearmor -o /etc/apt/keyrings/docker.gpg
    sudo chmod a+r /etc/apt/keyrings/docker.gpg
fi

echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu \
  $(. /etc/os-release && echo "$VERSION_CODENAME") stable" | \
  sudo tee /etc/apt/sources.list.d/docker.list > /dev/null

sudo apt-get update -y
sudo apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin

echo "=== 3. Adding current user to docker group ==="
sudo usermod -aG docker "$USER"

echo "=== 4. Installing AWS CLI v2 ==="
if ! command -v aws &> /dev/null; then
    curl -s "https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip" -o "awscliv2.zip"
    sudo apt-get install -y unzip
    unzip -q awscliv2.zip
    sudo ./aws/install
    rm -rf aws awscliv2.zip
    echo "AWS CLI v2 installed successfully."
fi

echo "=== 5. Docker Version Check ==="
docker --version
aws --version

echo "=============================================================================="
echo "Setup Complete!"
echo "To initialize Docker Swarm as MANAGER, run:"
echo "    sudo docker swarm init --advertise-addr <PRIVATE_IP>"
echo ""
echo "To join as a WORKER node, run the join command generated by the manager:"
echo "    sudo docker swarm join --token <TOKEN> <MANAGER_PRIVATE_IP>:2377"
echo "=============================================================================="
